            - **위험군**: 고령자, 치매가 있는 사람, 수술 환자
            - **응급 여부**: **의학적 응급**이다. 원인을 찾아 교정하는 것이 가장 중요하다.

            # 치매(주요 신경인지장애)
            - **발병**: **서서히** 시작해 수개월에서 수년에 걸쳐 진행한다.
            - **경과**: 대부분 **진행성이고 비가역적**이다(알츠하이머병, 혈관성 치매 등).
            - **핵심 증상**
              - **의식은 맑다.**
              - 기억장애가 나타나며, 최근 기억부터 잃는다.
              - 인지기능 장애
                - 실어증: 말을 이해하거나 표현하지 못한다.
                - 실행증: 동작을 수행하지 못한다.
                - 실인증: 사물이나 사람을 알아보지 못한다.
                - 실행기능 장애: 계획하고 판단하지 못한다.
              - 지남력 장애가 시간, 장소, 사람 순으로 진행한다.
            - **행동심리증상(BPSD)**
              - 배회, 초조, 공격성
              - 의심, 망상(물건을 도둑맞았다는 망상)
              - 우울, 수면장애
              - **해질녘증후군(sundowning)**: 해질녘과 밤에 혼란과 초조가 심해진다.
            - **대처 방식**
              - 기억의 빈틈을 채우려고 **작화증**을 보인다.
              - 기억하지 못하는 것을 숨기려고 **파국반응**을 보인다. 해내지 못할 일을 요구받으면 갑자기 울거나 화를 낸다.
            - **치료 약물**
              - 콜린에스테라제 억제제: 도네페질, 리바스티그민, 갈란타민
              - NMDA 길항제: 메만틴
              - 진행을 늦추는 약이며, 완치하는 약은 아니다.

            # 구별 요점
            - **급격하고 의식이 흐리며 변동**하면 섬망이다.
            - **서서히 오고 의식이 맑으며 진행**하면 치매이다.
            - 치매가 있는 노인에게 섬망이 겹칠 수 있다. 치매 환자가 갑자기 나빠지면 섬망을 의심한다.

            # 2. 간호사정

            # 섬망
            - 의식 수준, 주의력, 지남력을 **하루에도 여러 번 반복**해서 사정한다.
            - 선별도구: CAM, 중환자실에서는 CAM-ICU를 쓴다.
            - 원인을 사정한다.
              - 활력징후, 산소포화도
              - 섭취량과 배설량, 탈수
              - 검사 결과: 전해질, 혈당, 감염 지표
              - 투약 목록, 특히 항콜린제와 진정제
              - 통증, 배뇨와 배변(요정체, 변비)
              - 음주력
            - 착각, 환시, 초조를 관찰한다. 낙상하거나 관을 빼는 등 안전 위험을 확인한다.

            # 치매
            - 인지 기능: MMSE(K-MMSE), MoCA, CDR
            - 일상생활 수행능력: ADL, IADL
            - 행동심리증상: 배회, 공격성, 수면, 망상, 우울
            - 안전 위험: 낙상, 길 잃음, 화재, 약물 오용
            - 영양과 연하 상태, 배설
            - 남아 있는 능력과 강점, 생활력(습관과 선호)
            - **가족 돌봄자의 부담**과 소진

            # 간호진단
            - 급성 혼란(섬망), 만성 혼란(치매)
            - **상해(손상) 위험** (2020-100), 낙상 위험
            - 사고과정 장애, 언어적 의사소통 장애
            - 자가간호 결핍, 수면양상 장애, 영양 불균형
            - 배회
            - 돌봄자 역할 긴장

            # 3. 공통 간호중재: 섬망과 치매 모두에 해당

            # ① 환경: 안전하고, 자극이 적고, 일관되게
            - **적절한 조명**을 유지한다.
              - 밤에는 은은한 **야간등**을 켠다.
              - 어두우면 착각, 환시, 해질녘 혼란, 낙상이 심해진다.
              - **"밤에 조명을 끈다", "어둡게 한다"는 항상 오답**이다 (2026-100, 2024-100, 2023-100, 2020-100).
            - **자극이 적고 조용한 환경**을 유지한다 (2020-100).
              - 소음, TV, 사람의 출입을 줄인다.
              - 방문객은 **익숙한 소수**로 제한한다 (2023-100). "다양한 방문객 허용"은 오답이다.
            - **같은 간호사가 일관되게** 돌본다 (2026-100, 2024-100, 2020-100).
              - "돌보는 사람을 자주 바꾼다", "매일 새로운 간호사"는 오답이다.
            - 가구와 물건의 **위치를 바꾸지 않는다** (2026-100).
            - 낙상을 예방한다.
              - 침대를 낮추고 바퀴를 잠근다.
              - 바닥의 장애물을 치운다.
              - 미끄럼 방지 신발을 신긴다.
              - 호출벨은 손이 닿는 곳에 둔다.
            - 억제대는 되도록 쓰지 않는다. 초조와 손상이 커진다.
              - 가까이서 관찰하고, 가족이 함께 있게 하는 방법을 먼저 쓴다.

            # ② 지남력 제공과 감각 보조
            - **시간, 장소, 사람을 자주 알려 준다** (2024-100).
              - 예: "지금은 오후 3시이고, 여기는 ○○병원입니다. 저는 간호사 ○○입니다."
            - **숫자가 크고 잘 보이는** 시계와 달력을 둔다 (2026-100, 2023-100).
              - "시계와 달력을 두지 않는다", "숫자가 작은 시계"는 오답이다.
            - **안경, 보청기, 틀니, 지팡이를 환자 곁에** 둔다 (2024-100).
              - 감각 입력이 줄면 혼란이 커진다.
              - "간호사실에 보관한다"는 오답이다.
            - 가족사진이나 익숙한 물건을 두어 안정감을 준다.

            # ③ 의사소통
            - **짧고 간단하며 구체적인 말**로 한다 (2023-100, 2021-100).
            - **한 번에 한 가지씩, 천천히** 지시한다 (2022-100).
            - **낮고 차분한 목소리**로 말한다.
              - 높은 톤이나 고함은 화난 것으로 받아들인다 (2022-100, 2021-100).
              - 청력이 떨어졌다면 크게 말하기보다 정면에서 또박또박 말한다.
            - 이름을 부르고 정면에서 눈을 맞춘 뒤 말을 건다.
            - **"예/아니요"로 답할 수 있는 질문**이나 두 가지 중 하나를 고르는 질문을 한다.
              - 개방형 질문, 추상적인 단어, 복잡한 의사결정 요구는 좌절을 일으킨다 (2021-100).
            - 말로 하면서 몸짓, 시범, 그림을 함께 쓴다.

            # ④ 기본 욕구와 수면
            - 수분과 영양을 공급한다. 섭취량과 배설량을 확인한다.
            - 규칙적으로 배변하고 배뇨하도록 돕는다.
            - 통증을 조절한다.
            - 낮에는 깨어서 활동하고 밤에는 자도록 **수면-각성 주기를 유지**한다.
              - 낮잠을 줄인다.
              - 낮에는 커튼을 열어 햇빛을 받게 한다.

            # 4. 섬망의 간호중재 (특히 중요한 것)
            - **원인을 찾아 교정**하는 것이 가장 중요하다.
              - 감염을 치료한다.
              - 수분과 전해질을 교정한다.
              - 산소를 공급한다.
              - 원인 약물을 중단하거나 조정한다.
            - **진정제는 일차 중재가 아니다** (2024-100).
              - 벤조다이아제핀은 섬망을 악화시킬 수 있다.
              - 예외는 알코올 금단 섬망이다. 이때는 벤조다이아제핀을 쓴다.
              - 자신이나 남을 해칠 위험이 크면 처방에 따라 **저용량 항정신병약물**(할로페리돌 등)을 쓴다.
            - 착각과 환시에 대처한다.
              - 논쟁하지 않는다.
              - "무섭게 느껴지시는군요. 저것은 창밖의 나뭇잎입니다"처럼 감정을 인정하고 짧게 현실을 알려 준다 (2025-100).
            - 초조하면 곁에 있어 주고 안심시킨다. 가능하면 가족이 함께 있게 한다.
            - 조기에 움직이게 한다. 불필요한 도관과 관을 빨리 제거한다.
            - 회복된 뒤에는 대상자와 가족에게 **섬망은 일시적이었다**고 설명해 불안을 줄인다.

            # 5. 치매의 간호중재 (특히 중요한 것)

            # 일상의 구조화
            - **일과를 규칙적이고 일관되게** 유지한다 (2026-100). 치매 환자는 새로운 상황에 적응하는 능력이 떨어진다.
            - 익숙한 것을 유지한다. **새로운 지식이나 복잡한 활동은 피한다** (2022-100).
            - **단순하고 성공할 수 있는 활동**을 제공한다. 성취감을 주고 좌절을 막는다.

            # 자가간호
            - 남아 있는 능력은 **스스로 하게 한다.**
            - 단계를 나누어 한 가지씩 안내한다.
            - 옷은 입는 순서대로 놓아 둔다.
            - 식사는 **한 번에 조금씩**, 한 가지씩 제공한다 (2022-100). 삼킴을 관찰한다.

            # 배회
            - **안전한 범위 안에서 배회를 허용**한다 (2020-100).
              - 병실에만 가두거나 억제하면 초조가 커진다.
            - 배회에는 이유가 있으므로 확인한다: 배고픔, 배설, 통증, 지루함.
            - 출입구에 경보장치를 달고, 이름표나 위치 추적 장치를 쓴다.
            - 산책처럼 규칙적인 활동을 한다.

            # 초조와 공격성, 파국반응
            - 원인(자극, 피로, 통증, 좌절)을 찾아 제거한다.
            - 맞서거나 논쟁하지 않는다.
            - 차분하게 **관심을 다른 곳으로 돌린다(전환).**
            - 해질녘증후군이 있으면 오후에 활동과 자극을 줄이고 조명을 밝게 한다.

            # 기억 문제와 망상
            - 기억하지 못하는 것을 따지거나 시험하지 않는다.
              - "기억 안 나세요?"라고 묻지 않는다.
            - 물건을 도둑맞았다는 망상에는 함께 찾아 준다. 물건은 늘 같은 자리에 둔다.

            # 치료적 활동
            - **회상요법**: 과거의 즐거운 기억을 이야기하게 해 자존감을 높인다.
            - **현실지남력훈련**: 경증일 때 쓴다.
            - **인정요법(validation)**: 중증일 때 감정을 인정하는 방법이다.
            - 음악요법, 미술요법, 단순한 집단활동도 도움이 된다 (2020-100). 집단치료를 제한하는 것은 오답이다.

            # 가족 지지
            - 질병의 경과와 돌봄 방법을 교육한다.
            - 돌봄자가 소진되었는지 사정한다.
            - 주간보호, 단기보호, 장기요양서비스, 가족 지지모임을 연결한다.
            - 가정 안전 교육
              - 가스밸브와 약을 관리한다.
              - 낙상 위험 요소를 없앤다.
              - 야간등을 켠다.
              - 가구를 옮기지 않는다.

            # 6. 국시에 나온 오답 유형
            **치매 가족교육** (2026-100)
            - 밤에 조명을 끔: 해질녘 혼란과 낙상 위험이 커진다.
            - 돌보는 사람을 자주 바꿈: 일관성이 깨진다.
            - 숫자가 작은 시계: 크고 잘 보이는 시계가 필요하다.
            - 가구 위치를 바꿈: 혼란과 낙상 위험이 커진다.
            **수술 후 섬망** (2024-100)
            - 진정제 투여: 섬망이 악화될 수 있어 일차 중재가 아니다.
            - 간호사를 자주 바꿈: 일관성이 깨진다.
            - 조명을 끔: 착각이 심해진다.
            - 안경과 보청기를 간호사실에 보관: 감각 입력이 줄어 혼란이 커진다.
            **섬망 일반** (2023-100)
            - 조명을 어둡게 함
            - 다양한 방문객 허용
            - 한 번에 여러 가지 지시
            - 시계와 달력을 치움
            **치매 일반** (2022-100)
            - 한 번에 많은 음식 제공
            - 최신 지식 제공
            - 고함치듯 말함
            - 복잡한 활동 제공
            **치매 의사소통** (2021-100)
            - 높은 톤
            - 추상적인 단어
            - 개방형 질문
            - 의사결정을 요구하는 질문
            **치매 상해 위험** (2020-100)
            - 병실을 어둡게 함
            - 활동 범위를 병실로 제한함
            - 집단치료 제한
            - 매일 새로운 간호사

            # 7. 국시 풀이 요령
            - 보기에 **조명**이 나오면 "밝게" 또는 "은은한 야간등"이 맞다. **"끈다", "어둡게"는 무조건 오답**이다.
            - **사람과 환경은 일관되게** 유지한다. "자주 바꾼다", "새로운"이 들어간 보기는 오답이다.
            - **말은 짧고 간단하고 구체적으로, 한 번에 한 가지씩, 천천히, 낮은 톤으로** 한다.
              - "여러 가지", "추상적", "개방형", "큰 소리", "복잡한"은 오답이다.
            - **감각 보조기구는 환자 곁에, 시계와 달력은 크게** 둔다.
            - **자극은 적게** 한다. 다만 격리하거나 활동을 완전히 막는 것은 오답이다.
            - 수술 후 노인이 갑자기 "감옥에 가뒀다"고 하면 **섬망**이다. 지남력을 제공하는 보기를 고른다.
            - 섬망 환자가 나뭇잎을 귀신으로 보면 **착각**이다. 실제 자극이 있으면 착각, 없으면 환각이다 (2025-100).

            # 8. 앱의 관련 문항
            **섬망과 치매** (중재, 6문항)
            - 2026-100 치매 노인의 가족 교육 → 일상생활을 규칙적으로 유지한다
            - 2024-100 수술 후 중환자실에서 "감옥에 가뒀다"는 노인 → 시간, 장소, 사람을 자주 알려 준다
            - 2023-100 섬망 환자의 간호중재 → 구체적인 용어로 대화한다
            - 2022-100 치매 환자의 간호중재 → 한 번에 한 가지씩 천천히 지시한다
            - 2021-100 기억장애, 배회, 분노가 있는 75세 여자와의 의사소통 → 간단한 문장을 쓴다
