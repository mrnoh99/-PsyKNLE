            예: 간호사를 "최고"라고 하다가, 그 간호사가 규칙을 지키게 하자 "최악"이라고 한다.

            # 상징화 (symbolization)
            억압된 충동이나 감정을 상징으로 대신 나타내는 것이다.
            예: 누군가를 해치고 싶은 억압된 충동과 관련해 무의식적으로 빨간 옷을 입는다.

