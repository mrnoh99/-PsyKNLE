            예: 노출 충동을 무용 안무로 표현한다.

            # 억압 (repression)
            고통스러운 경험이나 용납되지 않는 충동을 무의식적으로 의식 밖으로 밀어내는 것이다. 해리성 기억상실의 주된 방어기제이다.
            예: 근친 성폭력 피해자가 가해자를 미워하지만 그 이유를 기억하지 못한다.

            # 전치 (displacement)
            감정을 원래 대상에게서 덜 위협적인 다른 대상에게 옮겨 표출하는 것이다.
            예: 배우자에게 화가 나서 대신 개를 찬다. 화가 나서 상대가 아닌 책상을 친다.
            국시: 2026-72 (남편에게 맞고 화가 나면 아이에게 소리를 지름)

            # 전환 (conversion)
            억압된 충동과 감정으로 생긴 불안이 감각이나 운동 기능의 신체 증상으로 바뀌는 것이다. 전환장애의 방어기제이다.
            예: 외상 경험을 다루는 치료를 앞두고 심한 두통이 생겨 치료를 취소한다. 화가 나서 한 대 치려는 순간 손이 마비된다.

            # 주지화 (intellectualization)
            감정을 느끼는 대신 지적으로 분석하고 따지며 대처하는 것이다.
            국시: 2025-72 (오답 보기)

            # 취소 (undoing)
            용납되지 않는 행동이나 생각을 상징적인 행동으로 없던 일로 되돌리려는 것이다. 강박장애의 대표적인 방어기제로, 오염에 대한 생각 뒤에 반복해서 손을 씻는 것이 한 예이다.
            예: 아침에 부인과 싸운 남편이 귀가할 때 선물을 사 간다.
            국시: 2020-72, 2025-93 (강박장애 환자가 불안을 줄이려고 사용하는 방어기제)

            # 퇴행 (regression)
            스트레스를 받을 때 이전의 낮은 발달 수준으로 돌아가는 것이다.
            예: 배변 훈련이 끝난 아이가 부모의 이혼 뒤 다시 오줌을 싼다.

            # 투사 (projection)
            받아들이기 어려운 자신의 감정, 충동, 책임을 다른 사람의 것으로 돌리는 것이다. 편집증에서 흔하다.
            예: "내가 그를 미워한다" 대신 "그가 나를 미워한다"고 여긴다.
            국시: 2021-71 (술을 마신 것이 아내의 잔소리 때문이라는 알코올 중독 환자)

