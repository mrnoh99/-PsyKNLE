            - 정답은 **영양 상태 회복**이다.
            **식욕부진증 입원 초기** (2023-101)
            - 이뇨제 허용, 운동 격려, 요구할 때 관장, 요구할 때마다 체중 측정은 오답이다.
            - 정답은 **매일 섭취량과 배설량 확인**이다.
            **식욕부진증 중재** (2022-101)
            - 운동량 증가, 날씬한 몸매 칭찬, 하루에 여러 번 체중 측정, 한 번에 많은 식사는 오답이다.
            - 정답은 **식사 후 1~2시간 화장실 제한**이다.
            **식욕부진증 우선 간호진단** (2020-101)
            - 지식 부족, 의사결정 갈등, 피부 통합성 장애, 상황적 자존감 저하는 우선이 아니다.
            - 정답은 **영양 불균형: 신체요구량보다 적음**이다.
            **폭식증의 특징** (2024-101)
            - 솜털 증가, 심한 저체온은 식욕부진증의 증상이다.
            - 완벽주의도 식욕부진증에 가까운 특성이다.
            - 신체상에 무관심하다는 것은 틀렸다.
            - 정답은 **식사 조절감 상실**이다.
