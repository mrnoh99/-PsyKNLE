            - E: 효과로서 합리적 신념과 새로운 감정이 생긴다.
            "반드시", "절대로" 같은 비합리적 신념을 논박해 바꾼다.

            # 3. 인지행동치료의 특징
            **현재의 역기능적 사고와 부적응 행동**을 바꾸는 데 초점을 둔다. 구조화되어 있고 단기간이며, 목표가 분명하고 과제를 준다.
            과거, 무의식적 갈등, 성격과 방어기제의 수정에 초점을 두는 것은 정신분석적 치료이다. 교정적 대인관계 경험은 대인관계치료의 특징이다.
            국시: 2021-77

            # 4. 헷갈리기 쉬운 짝
            - **체계적 탈감작 vs 홍수법**: 약한 자극부터 단계적으로 노출하면 체계적 탈감작, 가장 강한 자극에 바로 노출하면 홍수법이다.
            - **토큰경제 vs 형성법**: 토큰을 모아 보상과 바꾸면 토큰경제, 목표에 가까워지는 단계마다 강화하면 형성법이다.
            - **인지재구성 vs 사고중지법**: 생각을 따져서 바꾸면 인지재구성, 생각을 "중지"로 끊으면 사고중지법이다.
            - **혐오요법 vs 처벌**: 혐오요법은 문제 행동을 불쾌한 자극과 짝짓는 것이다(예: 다이설피람).

