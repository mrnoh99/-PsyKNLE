            # ② 폭식과 보상행동의 중단
            - 규칙적인 식사 계획을 세운다. 하루 세 끼와 간식을 정해진 시간에 먹는다.
              - 굶으면 폭식이 생긴다. 굶기와 폭식의 악순환을 끊는다.
            - 식사 후 화장실 사용을 제한하고 관찰해 구토를 막는다.
            - 설사제, 이뇨제, 과도한 운동을 제한한다.
            - **식사 일지**를 쓰게 한다.
              - 언제, 무엇을 먹었는지 기록한다.
              - 폭식 전후의 상황, 감정, 생각을 기록한다.
              - 폭식을 촉발하는 요인(스트레스, 외로움, 분노)을 찾는다.

            # ③ 대처 방법의 교육
            - 폭식 충동이 들 때 할 수 있는 대체 행동을 찾는다: 산책, 전화, 음악, 이완.
            - 감정을 말로 표현하도록 격려한다.
            - 스트레스 관리, 자기주장훈련, 문제해결 기술을 가르친다.

            # ④ 심리 치료와 약물
            - **인지행동치료**가 1차 치료이다.
              - 체형과 체중에 좌우되는 자존감, 흑백논리를 수정한다.
            - 비판하지 않고 수용한다. 수치심과 죄책감을 다룬다.
            - **SSRI**(fluoxetine)가 폭식과 구토를 줄인다.
            - 우울과 충동성, 물질 사용, 자해 위험을 사정한다.
            - 집단치료와 자조모임에 참여하게 한다.

            # 5. 국시에 나온 오답 유형
            **식욕부진증의 특징** (2026-101)
