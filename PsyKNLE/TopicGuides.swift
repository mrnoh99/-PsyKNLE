            # 강화, 처벌, 소거
            - **정적 강화**: 바람직한 행동 뒤에 좋은 것을 주어 그 행동을 늘린다.
            - **부적 강화**: 바람직한 행동 뒤에 싫은 것을 없애 주어 그 행동을 늘린다.
            - **처벌**: 문제 행동 뒤에 불쾌한 결과를 주어 그 행동을 줄인다.
            - **소거**: 문제 행동에 주던 강화(관심)를 끊어 그 행동을 줄인다. 예: 관심을 끌려는 행동에 반응하지 않는다.

            # 타임아웃 (time-out)
            문제 행동을 할 때 잠시 강화가 없는 곳에 있게 한다. 아동에게 많이 쓴다.

            # 형성법 (조형, shaping)
            목표 행동에 조금씩 가까워지는 행동마다 강화해서 복잡한 행동을 단계적으로 익히게 한다.

            # 모델링 (modeling)
            다른 사람의 행동을 관찰하고 따라 하며 배우게 한다.
            예: 낯선 곳을 방문하는 다른 사람의 모습을 보고 따라 하게 한다.

            # 행동계약 (contracting)
            목표 행동과 그에 따른 보상과 결과를 대상자와 미리 약속한다.

            # 이완훈련
            - 점진적 근육이완법: 근육을 차례로 긴장시켰다가 풀어 몸의 이완을 익힌다.
            - 호흡법: 복식호흡, 천천히 길게 내쉬기
            - 심상법

            # 바이오피드백 (biofeedback)
            심박, 근육 긴장, 피부 온도 같은 생리 반응을 기계로 보여 주어 스스로 조절하도록 훈련한다. 긴장성 두통, 불안에 쓴다.

            # 주장훈련 (assertiveness training)
            다른 사람의 권리를 침해하지 않으면서 자기 생각과 감정을 솔직하게 표현하는 법을 익히게 한다.

            # 사고중지법 (thought stopping)
            원치 않는 생각이 떠오를 때 마음속으로 "중지!"라고 외치며 생각을 끊는다. 인지적 요소가 섞인 행동 기법이다.
            국시 오답 보기: 2023-93, 2020-91 ("낯선 장소에서 불안할 때 마음속으로 '중지'라고 외친다")

            # 2. 인지치료

            # 벡(Beck)의 인지치료
            - 상황 자체보다 상황을 해석하는 **자동적 사고**가 감정을 만든다고 본다.
            - 우울한 사람은 자신, 세상, 미래를 모두 부정적으로 본다(**인지 삼제**).
            - 자동적 사고를 찾아 근거를 검토하고, 더 현실적인 생각으로 바꾸게 한다.

            # 인지재구성 (인지재구조화, cognitive restructuring)
            비합리적이고 왜곡된 생각을 찾아, 근거를 따져 보고, 합리적이고 현실적인 생각으로 바꾸는 기법이다.
            예: "나는 한 번도 제대로 해낸 적이 없어요. 이번에도 분명히 망칠 거예요"라며 활동을 거부하는 우울 환자
            국시: 2025-88

            # 주요 인지왜곡
            - **과잉일반화**: 한두 번의 일로 모든 상황에 대한 결론을 내린다.
              예: 한 번 실연했으니 앞으로도 모든 관계에서 실연할 것이다.
              국시: 2023-77
            - **흑백논리(이분법적 사고)**: 모든 것을 완전한 성공 아니면 완전한 실패로 본다.
            - **개인화**: 자신과 관련 없는 일을 자기 탓으로 여긴다.
            - **독심술**: 근거 없이 남이 자신을 나쁘게 생각한다고 단정한다.
            - **예언자적 오류(점쟁이 오류)**: 근거 없이 나쁜 결과를 확신한다.
            - **선택적 추상화**: 일부 부정적인 부분만 보고 전체를 판단한다.
            - **임의적 추론**: 근거 없이 결론을 내린다.
            - **극대화와 극소화**: 부정적인 일은 크게, 긍정적인 일은 작게 본다.
            - **파국화**: 일어날 수 있는 가장 나쁜 결과를 예상한다.
            - **당위적 사고**: "반드시 ~해야 한다"는 생각에 매인다.

            # 엘리스(Ellis)의 합리적 정서행동치료 (REBT, ABCDE 모형)
            - A: 선행사건
            - B: 비합리적 신념
